#!/usr/bin/env python3
"""
Generate the edition's strings for the resident string lookup.

In a level the game answers msg_string(id) from the level program's own
text block (one per language, loaded with the level), not from the global
text table, so new strings cannot simply be added to a file: level blocks
have no room to grow. Instead src/text.c takes over msg_string: ids in the
edition's range come from the tables generated here, everything else goes
to the game's own lookup.

Reads text/strings.tsv (`id<TAB>English[<TAB>French<TAB>German<TAB>Spanish
<TAB>Italian]`, ids in hex, consecutive from EE_TEXT_FIRST; a missing
language falls back to English) and writes build/modseg/gen_text.c with
`ee_text_first`, `ee_text_count` and `ee_text[count][8]` indexed by the
game's language id (0 English, 2 French, 3 German, 4 Spanish, 5 Italian).

  python tools/gen_text.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
COLUMN_TO_LANGUAGE = {1: 0, 2: 2, 3: 3, 4: 4, 5: 5}


def c_string(s: str) -> str:
    # The game's font has its own codes for accented letters; until that
    # code page is mapped, non-ASCII becomes its closest ASCII letter.
    # `\xNN` in the table is a font control code (button glyphs: 0x10 Cross,
    # 0x11 Circle, 0x12 Triangle, 0x13 Square, 0x14 L1, 0x15 R1, 0x18/0x19
    # the sticks), written as an octal escape so the letter after it is
    # never read as part of the escape.
    import re
    import unicodedata
    plain = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    plain = plain.replace("\\\\", "\0").replace('"', '\\"')
    plain = re.sub(r"\\x([0-9A-Fa-f]{2})", lambda m: "\\%03o" % int(m.group(1), 16), plain)
    return '"' + plain.replace("\0", "\\\\") + '"'


def main() -> int:
    rows = []
    for line in (ROOT / "text/strings.tsv").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.rstrip("\n").split("\t")
        rows.append((int(cols[0], 16), cols))
    rows.sort()
    first = rows[0][0]
    for i, (sid, _) in enumerate(rows):
        if sid != first + i:
            raise SystemExit(f"ids must be consecutive from 0x{first:X}; 0x{sid:X} is out of place")
    out = ["/* generated by tools/gen_text.py from text/strings.tsv; see src/text.c */",
           f"const int ee_text_first = 0x{first:X};",
           f"const int ee_text_count = {len(rows)};",
           f"const char *const ee_text[{len(rows)}][8] = {{"]
    for sid, cols in rows:
        langs = [None] * 8
        for col, lang in COLUMN_TO_LANGUAGE.items():
            langs[lang] = cols[col] if col < len(cols) and cols[col] else cols[1]
        out.append("  { " + ", ".join(c_string(l) if l else "0" for l in langs) + f" }},  /* 0x{sid:X} */")
    out.append("};")
    (ROOT / "build/modseg").mkdir(parents=True, exist_ok=True)
    (ROOT / "build/modseg/gen_text.c").write_text("\n".join(out) + "\n")
    print(f"wrote build/modseg/gen_text.c: {len(rows)} strings from 0x{first:X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
