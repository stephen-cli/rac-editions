#!/usr/bin/env python3
"""
List each level's bolt-paying enemies for x1's death counts (src/bolt_multiplier.c).

The edition counts how often each placed enemy has died, as Going Commando does
(a nibble per enemy), and pays the bolt multiplier's bonus on a falling share of
its bolts by that count. A moby names its placement by its uid (moby + 0xB2,
from the placement record), which runs up to about 2,000 per level, so a nibble
per uid would not fit the save's spare page; the counts are kept for the
enemies only, in each level's order of uid, and a kill finds its enemy's slot
by binary search in the level's list.

An enemy here is a placement whose moby class has type 5 (a creature, the
s16 at class + 0x46, what the game's targeting and SetDeathBits's payout
test) and a bolt value, placed or after its mission (record + 0x10, + 0x14).
Spawners need nothing special: a spawner recycles a small pool of placed
enemies, each with its own uid, so their deaths count like any other's.

Read from the disc: each level's gameplay file (its moby block, gameplay
header + 0x44: a count at +0, 0x78-byte records from +0x10; record + 0x0C the
uid, + 0x10 the bolts, + 0x14 the post-mission bolts, + 0x18 the class) and its
moby class table (core index + 0x18). Writes:

  build/modseg/gen_enemy_ids.c   ee_enemy_ids: the levels' sorted uid lists, one after another;
                                 ee_enemy_first[20]: each level's first slot, and the total

  python tools/gen_enemy_ids.py [--openrac DIR]
"""
import argparse
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EDITOR = HERE.parents[2] / "common/openrac_editor"   # OpenRAC's disc readers, carried (common/deps.py)
ROOT = HERE.parent

GAMEPLAY_MOBYS = 0x44       # the gameplay header's offset of the moby block
MOBY_RECORD = 0x78
CLASS_TYPE = 0x46           # s16 in the class header
TYPE_CREATURE = 5
LEVELS = 19


def deaths_capacity() -> int:
    """Nibbles in the page block src/modseg.h gives the counts (EE_DEATHS_BYTES)."""
    text = (ROOT / "src/modseg.h").read_text()
    m = re.search(r"#define\s+EE_DEATHS_BYTES\s+(0x[0-9A-Fa-f]+)", text)
    if not m:
        raise SystemExit("EE_DEATHS_BYTES is not defined in src/modseg.h")
    return int(m.group(1), 16) * 2


def class_types(level) -> dict[int, int]:
    """Class id -> its type (the s16 at class + 0x46), for every class with a blob in the level."""
    out = {}
    for entry in level.table(0x18, 32):
        start, class_id = struct.unpack_from("<ii", entry)
        if start:
            out[class_id] = struct.unpack_from("<h", level.block(start), CLASS_TYPE)[0]
    return out


def enemy_uids(level) -> list[int]:
    types = class_types(level)
    gameplay = level.gameplay
    block = struct.unpack_from("<I", gameplay, GAMEPLAY_MOBYS)[0]
    count = struct.unpack_from("<I", gameplay, block)[0]
    uids = set()
    for i in range(count):
        record = block + 0x10 + i * MOBY_RECORD
        uid, bolts, bolts_after, class_id = struct.unpack_from("<iiii", gameplay, record + 0x0C)
        if uid >= 0 and (bolts > 0 or bolts_after > 0) and types.get(class_id) == TYPE_CREATURE:
            uids.add(uid)
    return sorted(uids)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--openrac", type=Path, default=ROOT.parents[2] / "OpenRAC")
    ap.add_argument("-o", "--out", type=Path, default=ROOT / "build/modseg/gen_enemy_ids.c")
    args = ap.parse_args()

    sys.path.insert(0, str(EDITOR))
    from disc import Disc
    from level import load_level

    lists = []
    with Disc(args.openrac / "games/rac1/baserom/SCES_509.16.iso") as disc:
        for info in disc.survey()["levels"]:
            lists.append((info["id"], enemy_uids(load_level(disc, info))))
    lists.sort()
    if [lvl for lvl, _ in lists] != list(range(LEVELS)):
        raise SystemExit(f"expected levels 0-{LEVELS - 1}, found {[lvl for lvl, _ in lists]}")
    total = sum(len(u) for _, u in lists)
    if total > deaths_capacity():
        raise SystemExit(f"{total} enemies need more than the {deaths_capacity()} counts EE_DEATHS_BYTES holds")
    if any(u > 0xFFFF for _, uids in lists for u in uids):
        raise SystemExit("a uid does not fit 16 bits")

    first, ids = [], []
    for _, uids in lists:
        first.append(len(ids))
        ids.extend(uids)
    first.append(len(ids))
    lines = ["/* generated by tools/gen_enemy_ids.py: each level's bolt-paying enemies (class type 5) by uid,",
             " * sorted; a level's slots are ee_enemy_first[level] up to ee_enemy_first[level + 1].",
             " * See src/bolt_multiplier.c */",
             f"const unsigned short ee_enemy_first[{LEVELS + 1}] = {{ {', '.join(map(str, first))} }};",
             f"const unsigned short ee_enemy_ids[{len(ids)}] = {{"]
    for i in range(0, len(ids), 16):
        lines.append("    " + ", ".join(map(str, ids[i:i + 16])) + ",")
    lines.append("};")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {total} enemies over {LEVELS} levels "
          f"({', '.join(str(len(u)) for _, u in lists)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
